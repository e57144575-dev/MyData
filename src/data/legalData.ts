export function buildRecommendation(answers: AssistantAnswers): AssistantRecommendation {
  const { dataType, platform, consent, resolution } = answers;

  const isCriminalRisk =
    dataType === 'private_life' ||
    consent === 'leak_or_hack' ||
    resolution === 'cannot_contact_threat';

  const isRefusalOrCopies =
    resolution === 'refused_or_ignored' || resolution === 'deleted_copies_remain';

  const urgencyLevel: AssistantRecommendation['urgencyLevel'] = isCriminalRisk
    ? 'urgent'
    : isRefusalOrCopies
      ? 'elevated'
      : 'standard';

  const urgencyLabel =
    urgencyLevel === 'urgent'
      ? 'Приоритетный порядок: усиленная защита и обращение в госорганы'
      : urgencyLevel === 'elevated'
        ? 'Эскалация: обращение в поддержку платформы и уполномоченный орган'
        : 'Стандартный порядок: фиксация и первичное требование об удалении';

  // Headline tailored to dataType + resolution
  let headline = 'Рекомендуемый порядок действий при неправомерной публикации данных';
  if (isCriminalRisk) {
    headline = 'Защита при утечке частной информации, угрозах или невозможности диалога';
  } else if (dataType === 'fake_profile') {
    headline = 'Действия при обнаружении поддельного аккаунта с вашими данными';
  } else if (dataType === 'photo_video' && resolution === 'not_contacted') {
    headline = 'Как добиться удаления фотографии или видео без лишнего конфликта';
  } else if (dataType === 'contacts_docs') {
    headline = 'Порядок действий при открытой публикации телефона, ИИН или списков';
  } else if (resolution === 'refused_or_ignored') {
    headline = 'Что делать, если владелец ресурса отказал или игнорирует обращение';
  } else if (resolution === 'deleted_copies_remain') {
    headline = 'Удаление копий и повторных публикаций на других площадках';
  }

  // Summary tailored to consent & context
  const summaryParts: string[] = [];
  if (consent === 'no_consent') {
    summaryParts.push(
      'Поскольку вы не давали согласия на публикацию, закон на вашей стороне: распространение персональных данных и изображения без разрешения нарушает базовые нормы законодательства РК.'
    );
  } else if (consent === 'withdraw_consent') {
    summaryParts.push(
      'Даже если согласие давалось ранее, вы имеете законное право отозвать его и потребовать прекращения обработки и удаления материалов.'
    );
  } else if (consent === 'uncertain_public') {
    summaryParts.push(
      'При съёмке на публичном мероприятии или использовании сервиса важно проверить, была ли публикация связана с целью события и не нарушает ли она ваше достоинство и частную жизнь. Вы вправе вежливо запросить удаление.'
    );
  } else if (consent === 'leak_or_hack') {
    summaryParts.push(
      'Доступ через взлом, тайную съёмку или утечку данных — серьёзное нарушение, при котором недостаточно ограничиваться обычной просьбой: важно немедленно сохранить доказательства и подключить компетентные органы.'
    );
  }

  if (platform === 'messenger_chat') {
    summaryParts.push(
      'В мессенджерах и студенческих чатах решающее значение имеют быстрая фиксация переписки до её удаления и привлечение администратора чата или куратора группы.'
    );
  } else if (platform === 'social_network') {
    summaryParts.push(
      'На онлайн-платформах параллельно с обращением к автору эффективно работает официальная форма жалобы на нарушение приватности или выдачу себя за другое лицо.'
    );
  } else if (platform === 'website_portal') {
    summaryParts.push(
      'Для веб-сайтов и открытых документов важно установить владельца домена или администрацию организации и направить официальное письменное требование.'
    );
  } else if (platform === 'unknown_forwarding') {
    summaryParts.push(
      'При анонимной пересылке необходимо фиксировать каждый доступный аккаунт-распространитель и обращаться за защитой в правоохранительные органы и службу поддержки платформы.'
    );
  }

  // Dynamic Steps
  const steps: AssistantRecommendation['steps'] = [];

  steps.push({
    order: '01',
    title: 'Срочно сохраните полные доказательства без редактирования',
    description:
      platform === 'messenger_chat'
        ? 'Сделайте скриншоты сообщений, пересылки, списка участников или профиля отправителя, а также запишите видео экрана с открытием чата и даты публикации.'
        : 'Сделайте полные скриншоты страницы так, чтобы были видны точный адрес (URL), дата, время и профиль автора, а также сохраните видеозапись экрана.',
  });

  if (dataType === 'fake_profile') {
    steps.push({
      order: '02',
      title: 'Подайте жалобу на «выдачу себя за другое лицо» в интерфейсе соцсети',
      description:
        'Используйте встроенную кнопку «Пожаловаться» → «Притворяется мной / Выдача себя за другого человека». Попросите одногруппников отметить аккаунт как фейковый и не вступать с ним в переписку.',
    });
  } else if (resolution === 'not_contacted' && !isCriminalRisk) {
    steps.push({
      order: '02',
      title: 'Направьте спокойное требование автору или администратору ресурса',
      description:
        consent === 'withdraw_consent'
          ? 'Письменно сообщите об отзыве ранее данного согласия со ссылкой на статьи 8 и 24 Закона РК № 94-V и попросите удалить публикацию.'
          : 'Напишите автору или администратору паблика вежливое сообщение с точной ссылкой на материал и указанием на отсутствие согласия (ст. 145 ГК РК и Закон РК № 94-V). Сохраните скриншот переписки.',
    });
  } else if (resolution === 'refused_or_ignored') {
    steps.push({
      order: '02',
      title: 'Сохраните факт отказа или игнорирования для официальной жалобы',
      description:
        'Зафиксируйте скриншотом отправленное вами требование, время прочтения и отказ (если он был). Это подтвердит, что вы пытались урегулировать ситуацию напрямую.',
    });
  } else if (resolution === 'deleted_copies_remain') {
    steps.push({
      order: '02',
      title: 'Соберите ссылки на все оставшиеся копии и репосты',
      description:
        'Пройдитесь по репостам, кэшу поисковых систем и другим каналам, чтобы составить единый перечень оставшихся URL-адресов для жалоб в поддержку каждой площадки.',
    });
  } else {
    steps.push({
      order: '02',
      title: 'Не вступайте в переговоры с вымогателями и усильте защиту аккаунтов',
      description:
        'Если присутствуют угрозы, шантаж или взлом, срочно смените пароли, включите двухфакторную аутентификацию и проверьте активные сеансы на всех своих устройствах. Ничего не переводите злоумышленникам.',
    });
  }

  if (platform === 'social_network' || platform === 'messenger_chat') {
    steps.push({
      order: '03',
      title: 'Используйте встроенную жалобу платформы и поддержку университета',
      description:
        platform === 'messenger_chat'
          ? 'Отправьте жалобу через меню сообщения в мессенджере. Если чат связан с вузом или общежитием, сообщите куратору группы, в деканат или студенческому омбудсмену.'
          : 'Отправьте жалобу в службу модерации соцсети (нарушение конфиденциальности / публикация личных данных без согласия). Если паблик студенческий — подключите администрацию вуза.',
    });
  } else {
    steps.push({
      order: '03',
      title: 'Обратитесь к владельцу сайта или в ответственное подразделение вуза',
      description:
        'Найдите контакты администрации ресурса (раздел «Контакты» или политика конфиденциальности) и направьте официальное электронное письмо с требованием закрыть доступ к документу или странице.',
    });
  }

  if (isCriminalRisk) {
    steps.push({
      order: '04',
      title: 'Обратитесь в полицию (102) и в Комитет по информационной безопасности',
      description:
        'При распространении сведений о частной жизни, тайной съёмке, взломе, шантаже или угрозах подайте заявление в органы внутренних дел (102 или через eOtinish.kz). Параллельно можно направить обращение в Комитет по информационной безопасности через eOtinish.kz.',
    });
  } else if (isRefusalOrCopies || dataType === 'contacts_docs') {
    steps.push({
      order: '04',
      title: 'Подайте официальное обращение через eOtinish.kz в Комитет по информационной безопасности',
      description:
        'Если публикацию не удалили или раскрыты защищаемые персональные данные (телефон, ИИН, адрес, списки), авторизуйтесь с помощью ЭЦП на eotinish.kz, выберите Комитет по информационной безопасности и приложите собранные скриншоты.',
    });
  } else {
    steps.push({
      order: '04',
      title: 'Эскалируйте через eOtinish.kz, если вопрос не решится в течение разумного срока',
      description:
        'Если модерация платформы и администратор ресурса не реагируют, сохраните переписку и направьте официальное обращение в Комитет по информационной безопасности через платформу eOtinish.kz с помощью ЭЦП.',
    });
  }

  // Legal refs
  const legalRefs: AssistantRecommendation['legalRefs'] = [
    {
      title: 'Закон РК № 94-V «О персональных данных и их защите» (ст. 1, 7, 8, 24)',
      note:
        consent === 'withdraw_consent'
          ? 'Закрепляет порядок отзыва согласия (ст. 8) и право требовать блокирования/уничтожения данных (ст. 24).'
          : 'Закрепляет обязательность согласия на сбор и распространение данных и право требовать их удаления.',
      url: 'https://adilet.zan.kz/rus/docs/Z1300000094',
    },
  ];

  if (dataType === 'photo_video' || dataType === 'fake_profile') {
    legalRefs.push({
      title: 'Гражданский кодекс РК, статья 145 «Право на собственное изображение»',
      note: 'Запрещает использование, опубликование и распространение фото или видео человека без его согласия.',
      url: 'https://adilet.zan.kz/rus/docs/K940001000_',
    });
  }

  if (isCriminalRisk) {
    legalRefs.push({
      title: 'Уголовный кодекс РК, статья 147 и Конституция РК, статья 18',
      note: 'Защита неприкосновенности частной жизни, личной тайны и ответственность за распространение данных, причинившее существенный вред, в том числе на онлайн-платформах.',
      url: 'https://adilet.zan.kz/rus/docs/K1400000226',
    });
  } else {
    legalRefs.push({
      title: 'КоАП РК, статья 79 «Нарушение законодательства о персональных данных»',
      note: 'Устанавливает административную ответственность за незаконный сбор и обработку персональных данных.',
      url: 'https://adilet.zan.kz/rus/docs/K1400000235',
    });
  }

  // Recommended channels
  const recommendedChannels: AssistantRecommendation['recommendedChannels'] = [];

  if (isCriminalRisk) {
    recommendedChannels.push({
      name: 'Полиция (экстренный номер 102 / МВД РК)',
      reason: 'При угрозах, шантаже, взломе или незаконном распространении сведений о частной жизни.',
      targetSection: 'authorities',
    });
  }

  recommendedChannels.push({
    name: 'Платформа eOtinish.kz и Комитет по информационной безопасности',
    reason: 'Для подачи официальной жалобы с ЭЦП и приложением доказательств нарушения Закона № 94-V.',
    externalUrl: 'https://eotinish.kz',
  });

  recommendedChannels.push({
    name: 'Подробный порядок действий и образец обращения',
    reason: 'Посмотрите шаблон нейтрального сообщения администратору и список частых ошибок.',
    targetSection: 'steps',
  });

  const precautions: string[] = [
    'Не удаляйте переписку и не редактируйте исходные скриншоты.',
    'Не публикуйте в ответ персональные данные других лиц.',
  ];
  if (isCriminalRisk) {
    precautions.push(
      'Не переводите деньги при шантаже и срочно включите двухфакторную аутентификацию в своих аккаунтах.'
    );
  } else if (consent === 'uncertain_public') {
    precautions.push(
      'Проверьте правила мероприятия или пользовательское соглашение площадки перед направлением жалобы.'
    );
  } else {
    precautions.push(
      'Поддерживайте спокойный и деловой тон в сообщениях, чтобы переписка могла служить доказательством.'
    );
  }

  return {
    urgencyLabel,
    urgencyLevel,
    headline,
    summary: summaryParts.join(' '),
    steps,
    legalRefs,
    recommendedChannels,
    precautions,
  };
}
